// pnpm assets:build (mw-e37.8): every model under assets/source/<category>/<id>/<id>.glb|.gltf becomes
// public/assets/model/<id>.glb (High) and public/assets/model/low/<id>.glb (Low, half-size textures),
// listed in public/assets/model/manifest.json with URLs, byte sizes, triangles and texture sizes.
// Incremental: a model whose source folder, settings and pipeline version hash to the manifest's
// sourceHash, and whose outputs are intact, is not rebuilt and nothing is written. A failing model
// leaves its previous outputs and manifest entry untouched and fails the run.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join } from 'node:path';
import { z } from 'zod';
import { buildConfig, settingsFor, type ModelSettings } from './config.ts';
import { AssetBuildError, buildTier, SUPPORTED_EXTENSIONS, type TierResult } from './pipeline.ts';

export const SOURCE_ROOT = 'assets/source';
export const MODEL_OUT = 'public/assets/model';
export const MANIFEST_PATH = `${MODEL_OUT}/manifest.json`;
/** Model formats recognised in a source folder; only SUPPORTED_EXTENSIONS build (convert the rest). */
export const MODEL_EXTENSIONS = [...SUPPORTED_EXTENSIONS, '.fbx', '.obj', '.dae', '.blend', '.usdz'];

export interface ModelSource {
  assetId: string;
  /** Repo-relative source folder and model file. */
  dir: string;
  file: string;
}

const tierEntry = z.strictObject({ url: z.string(), bytes: z.number(), textures: z.array(z.string()) });
const manifestEntry = z.strictObject({
  sourceHash: z.string(),
  triangles: z.number(),
  high: tierEntry,
  low: tierEntry,
});
export type ManifestEntry = z.infer<typeof manifestEntry>;
const manifestSchema = z.strictObject({
  $comment: z.string(),
  models: z.record(z.string(), manifestEntry),
});
export type Manifest = z.infer<typeof manifestSchema>;
const COMMENT =
  'Generated by pnpm assets:build (mw-e37.8); do not hand-edit. Asset id → High and Low runtime GLBs (meshopt + WebP).';

export interface BuildReport {
  built: string[];
  cached: string[];
  errors: string[];
}

const dirs = (path: string): string[] =>
  existsSync(path)
    ? readdirSync(path)
        .sort()
        .filter((name) => statSync(join(path, name)).isDirectory())
    : [];

/** Every assets/source/<category>/<id>/<id>.<model ext>, sorted by path. */
export function discoverModels(root: string): ModelSource[] {
  const found: ModelSource[] = [];
  for (const category of dirs(join(root, SOURCE_ROOT))) {
    for (const assetId of dirs(join(root, SOURCE_ROOT, category))) {
      const dir = `${SOURCE_ROOT}/${category}/${assetId}`;
      for (const ext of MODEL_EXTENSIONS) {
        const file = `${dir}/${assetId}${ext}`;
        if (existsSync(join(root, file))) found.push({ assetId, dir, file });
      }
    }
  }
  return found;
}

/** Hash of everything that decides a model's outputs: its folder's files, settings and pipeline. */
export function sourceHash(root: string, source: ModelSource, settings: ModelSettings): string {
  const hash = createHash('sha256');
  hash.update(JSON.stringify({ pipeline: buildConfig.pipelineVersion, settings }));
  for (const name of readdirSync(join(root, source.dir)).sort()) {
    const path = join(root, source.dir, name);
    if (!statSync(path).isFile()) continue;
    hash.update(`\0${name}\0`);
    hash.update(readFileSync(path));
  }
  return hash.digest('hex');
}

export function readManifest(root: string): Manifest {
  const path = join(root, MANIFEST_PATH);
  if (!existsSync(path)) return { $comment: COMMENT, models: {} };
  return manifestSchema.parse(JSON.parse(readFileSync(path, 'utf8')));
}

const intact = (root: string, entry: ManifestEntry): boolean =>
  [entry.high, entry.low].every((tier) => {
    const path = join(root, 'public', tier.url);
    return existsSync(path) && statSync(path).size === tier.bytes;
  });

/** Writes every file to a temporary name first, then renames them all, so a failure writes nothing. */
function writeAll(root: string, files: readonly (readonly [string, Uint8Array])[]): void {
  const temps = files.map(([path, bytes]) => {
    const temp = join(root, `${path}.tmp-${String(process.pid)}`);
    mkdirSync(dirname(temp), { recursive: true });
    writeFileSync(temp, bytes);
    return [temp, join(root, path)] as const;
  });
  for (const [temp, path] of temps) renameSync(temp, path);
}

function readSidecar(root: string, source: ModelSource): unknown {
  const path = `${source.dir}/build.json`;
  if (!existsSync(join(root, path))) return undefined;
  try {
    return JSON.parse(readFileSync(join(root, path), 'utf8'));
  } catch (error) {
    throw new AssetBuildError(`${source.assetId}: ${path}: ${(error as Error).message}`);
  }
}

const tier = (url: string, result: TierResult): ManifestEntry['high'] => ({
  url,
  bytes: result.glb.byteLength,
  textures: result.textures,
});

async function buildModel(root: string, source: ModelSource, previous: ManifestEntry | undefined) {
  const ext = extname(source.file);
  if (!(SUPPORTED_EXTENSIONS as readonly string[]).includes(ext)) {
    throw new AssetBuildError(
      `${source.assetId}: unsupported format ${ext} (${source.file}); convert it to .glb first`,
    );
  }
  const sidecarJson = readSidecar(root, source);
  let settings: ModelSettings;
  try {
    settings = settingsFor(source.assetId, sidecarJson);
  } catch (error) {
    throw new AssetBuildError(`${source.assetId}: ${source.dir}/build.json: ${(error as Error).message}`);
  }
  const sourceHashValue = sourceHash(root, source, settings);
  if (previous?.sourceHash === sourceHashValue && intact(root, previous)) {
    return { entry: previous, cached: true };
  }
  const input = join(root, source.file);
  const common = { maxTriangles: settings.maxTriangles, simplifyRatio: settings.simplifyRatio };
  const high = await buildTier(input, source.assetId, { ...common, textureSize: settings.textureSize });
  const low = await buildTier(input, source.assetId, { ...common, textureSize: settings.lowTextureSize });
  const highPath = `${MODEL_OUT}/${source.assetId}.glb`;
  const lowPath = `${MODEL_OUT}/low/${source.assetId}.glb`;
  writeAll(root, [
    [highPath, high.glb],
    [lowPath, low.glb],
  ]);
  const entry: ManifestEntry = {
    sourceHash: sourceHashValue,
    triangles: high.triangles,
    high: tier(`/${highPath.slice('public/'.length)}`, high),
    low: tier(`/${lowPath.slice('public/'.length)}`, low),
  };
  return { entry, cached: false };
}

/** Builds every source model; the manifest is rewritten only when it changes. */
export async function buildAll(root: string, log: (line: string) => void): Promise<BuildReport> {
  const manifest = readManifest(root);
  const report: BuildReport = { built: [], cached: [], errors: [] };
  const models: Record<string, ManifestEntry> = {};
  for (const source of discoverModels(root)) {
    const previous = manifest.models[source.assetId];
    try {
      const { entry, cached } = await buildModel(root, source, previous);
      models[source.assetId] = entry;
      (cached ? report.cached : report.built).push(source.assetId);
      if (!cached) {
        log(
          `built ${source.assetId}: ${String(entry.triangles)} tris, High ${String(entry.high.bytes)} B [${entry.high.textures.join(', ')}], Low ${String(entry.low.bytes)} B [${entry.low.textures.join(', ')}]`,
        );
      }
    } catch (error) {
      const message = (error as Error).message;
      report.errors.push(message.startsWith(`${source.assetId}:`) ? message : `${source.assetId}: ${message}`);
      if (previous !== undefined) models[source.assetId] = previous;
    }
  }
  const text = `${JSON.stringify({ $comment: COMMENT, models }, null, 2)}\n`;
  const path = join(root, MANIFEST_PATH);
  if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  return report;
}

/**
 * Builds one unapproved candidate (assets/_incoming/<id>/vN.glb from pnpm asset:gen-model) beside
 * itself as vN.runtime.glb and vN.runtime-low.glb, for the turntable gate to review what will ship.
 * No manifest, no cache.
 */
export async function buildCandidate(root: string, file: string): Promise<string[]> {
  const assetId = basename(dirname(file));
  const settings = settingsFor(assetId, undefined);
  const input = join(root, file);
  if (!existsSync(input)) throw new AssetBuildError(`${assetId}: ${file} does not exist`);
  const stem = file.slice(0, -extname(file).length);
  const common = { maxTriangles: settings.maxTriangles, simplifyRatio: settings.simplifyRatio };
  const high = await buildTier(input, assetId, { ...common, textureSize: settings.textureSize });
  const low = await buildTier(input, assetId, { ...common, textureSize: settings.lowTextureSize });
  const outputs = [`${stem}.runtime.glb`, `${stem}.runtime-low.glb`];
  writeAll(root, [
    [String(outputs[0]), high.glb],
    [String(outputs[1]), low.glb],
  ]);
  return [
    `${String(outputs[0])}: ${String(high.triangles)} tris, ${String(high.glb.byteLength)} B [${high.textures.join(', ')}]`,
    `${String(outputs[1])}: ${String(low.glb.byteLength)} B [${low.textures.join(', ')}]`,
  ];
}
