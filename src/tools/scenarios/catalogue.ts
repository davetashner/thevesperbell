// The emergence catalogue doc (mw-e03.27): docs/design/emergence-catalogue.md, generated from the
// scenario files so designers read exactly what CI replays. `pnpm scenarios:docs` rewrites it and
// tests/integration/emergence-catalogue-doc.test.ts fails when it is stale.

import type { Scenario, ScenarioInput, ScenarioOutcome } from './schema';

/** Where the catalogue doc lives, relative to the repo root. */
export const CATALOGUE_DOC = 'docs/design/emergence-catalogue.md';

const at = (point: string | readonly [number, number, number]): string =>
  typeof point === 'string' ? point : `(${point.join(', ')})`;

function describeInput(input: ScenarioInput): string {
  const when = `tick ${String(input.tick)}`;
  if ('stimulus' in input) {
    const s = input.stimulus;
    return `${when}: ${s.element} stimulus of ${String(s.intensity)} at ${at(s.at)} (radius ${String(s.radius)} m)`;
  }
  if ('blast' in input) {
    const b = input.blast;
    return `${when}: force blast of ${String(b.intensity)} at ${at(b.at)} (radius ${String(b.radius)} m)`;
  }
  return `${when}: set ${input.set.property} of ${input.set.target} to ${String(input.set.value)}`;
}

function describeOutcome(outcome: ScenarioOutcome): string {
  const target =
    'spawn' in outcome.target
      ? outcome.target.spawn
      : `${outcome.target.which} of the \`${outcome.target.tag}\` spawns`;
  return `tick ${String(outcome.tick)}: ${outcome.sees} (\`${outcome.reading}\` of ${target} ${outcome.op} ${String(outcome.value)})`;
}

/** The catalogue doc for `scenarios`, in the order given. */
export function renderCatalogue(scenarios: readonly Scenario[]): string {
  const lines = [
    '# Emergence catalogue',
    '',
    '<!-- Generated by `pnpm scenarios:docs` from tests/scenarios/*.json; do not edit by hand. -->',
    '',
    'Each scenario is a replayable combination of ordinary world properties in the greybox chaos room',
    '(`?scene=chaos-room`): the game fires real stimuli at props and the element rules, plates and ropes',
    'do the rest. Outcomes are properties read at ticks (60 ticks per second), never entity types. CI',
    'replays every scenario (`tests/integration/emergence-scenarios.test.ts`) and compares its final',
    'state hash with a golden; a broken combo names its scenario and what the player would have seen.',
    'New combos found in playtests are added as a file in `tests/scenarios/`; `pnpm scenarios:bless`',
    'records the golden hash and `pnpm scenarios:docs` regenerates this page.',
    '',
    `${String(scenarios.length)} scenarios.`,
    '',
    '| Scenario | Id | Elements and mechanisms |',
    '| --- | --- | --- |',
    ...scenarios.map((s) => `| [${s.title}](#${s.id}) | \`${s.id}\` | ${s.tags.join(', ')} |`),
    '',
  ];
  for (const s of scenarios) {
    lines.push(
      `## ${s.title}`,
      '',
      `<a id="${s.id}"></a>`,
      '',
      s.description,
      '',
      `Setup: ${s.setup.props}`,
      ...s.setup.properties.map(
        (p) => `- before the first tick: ${p.property} of ${p.target} is ${String(p.value)}`,
      ),
      '',
      'Inputs:',
      ...s.inputs.map((i) => `- ${describeInput(i)}`),
      '',
      'Outcomes:',
      ...s.outcomes.map((o) => `- ${describeOutcome(o)}`),
      '',
    );
  }
  return lines.join('\n');
}
